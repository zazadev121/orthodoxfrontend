// Refresh licensed metadata and a curated daily-verse rotation from AO Lab.
// Scripture text is kept unchanged; see the attribution in src/scripture.jsx.
import { writeFile } from 'node:fs/promises';
const base = 'https://bible.helloao.org/api';
const refs = [['JHN',3,16],['MAT',11,28],['PSA',23,1],['PHP',4,13],['JHN',14,27],['PRO',3,5],['ROM',8,28],['ISA',41,10],['PSA',119,105],['JOS',1,9],['1CO',13,4],['1PE',5,7],['2TI',1,7],['MAT',5,9],['JHN',8,12],['1JN',4,19],['HEB',13,8],['JAS',1,5],['GAL',5,22],['COL',3,14],['REV',21,4],['PSA',46,1],['ROM',15,13],['ISA',40,31],['1CO',13,13],['1TH',5,16],['1TH',5,17],['1TH',5,18],['HEB',11,1],['LUK',6,31],['MAT',6,33],['JHN',15,12],['2CO',5,7],['EPH',2,8],['PSA',34,8],['PSA',37,5],['PSA',121,2],['LAM',3,23],['PHP',4,6],['PHP',4,7]];
async function json(path) {
  const response=await fetch(`${base}/${path}`,{signal:AbortSignal.timeout(30000)});
  if(!response.ok)throw Error(`${path}: ${response.status}`);
  return response.json();
}
const editions=[];
for(const id of ['ckb_bib','eng_webu']) {
  const {translation,books}=await json(`${id}/books.json`);
  if(!translation.license || translation.license.commercialUse!=='allowed' || translation.license.derivatives!=='allowed')throw Error('Review translation license before refresh');
  const chapters=new Map();
  for(let start=0;start<refs.length;start+=5) {
    await Promise.all(refs.slice(start,start+5).map(async([book,chapter])=>{
      const key=`${book}/${chapter}`;
      if(!chapters.has(key))chapters.set(key,await json(`${id}/${key}.simple.json`));
    }));
  }
  const daily=refs.map(([book,chapter,verse])=>{
    const source=chapters.get(`${book}/${chapter}`);
    const row=source.chapter.content.find(x=>x.type==='verse' && x.number===verse);
    if(!row?.text)throw Error(`Verse missing: ${id}/${book}/${chapter}:${verse}`);
    return {book,chapter,verse,text:row.text};
  });
  editions.push({id,name:translation.name,englishName:translation.englishName,language:translation.language==='eng'?'en':'ckb',direction:translation.textDirection,licenseUrl:translation.licenseUrl,
    books:books.map(({id,name,order,firstChapterNumber,lastChapterNumber,isApocryphal})=>({id,name,order,firstChapterNumber,lastChapterNumber,...(isApocryphal?{isApocryphal:true}:{})})),daily});
  console.log(`${id}: ${books.length} books; ${daily.length} daily verses verified`);
}
await writeFile(new URL('../src/scripture-data.js',import.meta.url),'// Licensed source metadata and unchanged verse excerpts. Generated by scripts/refresh-scripture.mjs.\nexport const scriptureEditions = '+JSON.stringify(editions,null,2)+';\n');
