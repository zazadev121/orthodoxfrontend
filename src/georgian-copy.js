function flattenWords(value, prefix) {
  if (Array.isArray(value)) return Object.assign({}, ...value.map((v, i) => flattenWords(v, `${prefix}.${i}`)));
  if (value && typeof value === "object") return Object.assign({}, ...Object.entries(value).map(([k, v]) => flattenWords(v, `${prefix}.${k}`)));
  return { [prefix]: value };
}

